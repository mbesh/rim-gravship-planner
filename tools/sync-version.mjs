import {readFile,writeFile} from 'node:fs/promises';

const root=new URL('../',import.meta.url);
const {version}=JSON.parse(await readFile(new URL('package.json',root),'utf8'));
if(typeof version!=='string'||!/^\d+\.\d+\.\d+(?:-[\da-zA-Z.-]+)?(?:\+[\da-zA-Z.-]+)?$/.test(version)){
  throw new Error('package.json must contain a semantic release version.');
}
const target=new URL('version.js',root);
const expected=`// Generated by tools/sync-version.mjs from package.json.\nexport const APP_VERSION = '${version}';\n`;
const current=await readFile(target,'utf8').catch(error=>{if(error.code==='ENOENT')return '';throw error;});
if(current.replace(/\r\n/g,'\n')!==expected){
  if(process.argv.includes('--check'))throw new Error('version.js is stale. Run npm run sync:version.');
  await writeFile(target,expected);
}
